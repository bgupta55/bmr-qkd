"""
Q16 (part 1): generate results_macros.tex from JSON/CSV result files.
Every number in the .tex is computed here; none is hand-typed.
Regenerate with: python3 experiments/generate_macros.py
"""
import json, os, math, statistics, hashlib
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "data", "results")

def _ld(f):
    return json.load(open(os.path.join(RES, f)))

_DIG = {"0":"Zero","1":"One","2":"Two","3":"Three","4":"Four","5":"Five","6":"Six","7":"Seven","8":"Eight","9":"Nine"}

def cname(raw):
    """LaTeX control-sequence names may contain letters only."""
    out = "".join(_DIG.get(c, c) if c.isdigit() else c for c in raw)
    return "".join(c for c in out if c.isalpha())

def mc(name, value, comment="", fmt=None):
    if fmt is not None:
        s = format(value, fmt)
    elif isinstance(value, float):
        s = f"{value:.4g}"
    else:
        s = str(value)
    return fr"\newcommand{{\{cname(name)}}}{{{s}}} % {comment}"

lines = [
    "% RESULTS MACROS — generated by generate_macros.py; DO NOT EDIT BY HAND",
    "% " + "=" * 70,
    "% " + "source sha256: " + hashlib.sha256(open(__file__, "rb").read()).hexdigest()[:16],
    "", "% === Q4 COLLUSION ===",
]
q4 = _ld("q4_collusion.json")
for row in q4["rows"]:
    tp = row["topology"].upper(); rn = row["router"].replace("-", "").replace(" ", "").replace(".", "")
    lines.append(mc(f"qFourWorstCase{tp}{rn}", row["worst_case_pct"], fmt=".1f", comment= f"{row['topology']} {row['router']} worst-case P(min-relay<=1)%"))
lines += ["", "% === Q5 EVIDENCE SOURCE ==="]
q5 = _ld("q5_evidence_source.json")
for row in q5["rows"]:
    n, lt = row["n"], row["link"].replace("-", "").replace(" ", "")
    lines.append(mc(f"qFiveBMRAcceptN{n}{lt}", row["bmr_accept_pct"], f"n={n} {row['link']} BMR accept%", fmt=".2f"))
    lines.append(mc(f"qFiveBEightAcceptN{n}{lt}", row["b8_accept_pct"], f"n={n} {row['link']} B8 accept%", fmt=".2f"))
lines += ["", "% === Q6 SWEEP (router averages over all cells) ==="]
q6 = _ld("q6_sweep.json")
from collections import defaultdict
ragg = defaultdict(lambda: {"rate_f": [], "compl_f": [], "rate_bo": [], "compl_bo": []})
for row in q6["rows"]:
    k = row["router"]
    ragg[k]["rate_f"].append(row["mean_rate"]); ragg[k]["compl_f"].append(row["compl_pct"])
    ragg[k]["rate_bo"].append(row["mean_rate_budget_only"]); ragg[k]["compl_bo"].append(row["compl_budget_only_pct"])
for rtr, v in sorted(ragg.items()):
    rn = rtr.replace("lambda", "Lam")
    n_cells = len(v["rate_f"])
    lines.append(mc(f"qSixMeanRateFull{rn}", sum(v["rate_f"])/n_cells, f"{rtr} mean rate, full metric ({n_cells} cells)", fmt=".4f"))
    lines.append(mc(f"qSixComplFull{rn}", sum(v["compl_f"])/n_cells, f"{rtr} compliance %, full metric", fmt=".1f"))
    lines.append(mc(f"qSixMeanRateBudgetOnly{rn}", sum(v["rate_bo"])/n_cells, f"{rtr} mean rate, budget-only metric", fmt=".4f"))
    lines.append(mc(f"qSixComplBudgetOnly{rn}", sum(v["compl_bo"])/n_cells, f"{rtr} compliance %, budget-only", fmt=".1f"))
lines += ["", "% === Q9 SOLVER VALIDATION ==="]
q9 = _ld("q9_solver_validation.json")
lines.append(mc("qNineTotalInstances", q9["validation"]["total"], "total Q9 validation instances"))
lines.append(mc("qNineFeasible", q9["validation"]["feasible"], "feasible instances"))
lines.append(mc("qNineMismatches", q9["validation"]["mismatches"], "mismatches BMR vs brute-force"))
trow = q9["timing_rows"]
t10t1 = [r for r in trow if r["n"] == 10 and r["t"] == 1]; med10t1 = t10t1[0]["median_ms"] if t10t1 else 0
lines.append(mc("qNineMedianMsNtenTone", med10t1, "median ms n=10 t=1", fmt=".2f"))
t100t3 = [r for r in trow if r["n"] == 100 and r["t"] == 3]; med100t3 = t100t3[0]["median_ms"] if t100t3 else 0
lines.append(mc("qNineMedianMsNoneHundredTthree", med100t3, "median ms n=100 t=3", fmt=".1f"))
lines += ["", "% === Q8 HARDWARE (ten ibm_marrakesh runs) ==="]
q8 = _ld("q8_hardware_reconcile.json")
_c = _ld("q8_hw_refetched.json")["db659bklf4us73c4qju0"]["raw_counts_by_pub_index"][:4]  # 12 Oct run, phi = 0
_E = [(c["00"] + c["11"] - c["01"] - c["10"]) / sum(c.values()) for c in _c]
_s12 = _E[0] + _E[1] + _E[2] - _E[3]  # settings (0,0),(0,1),(1,0) positive; (1,1) negative
_s0 = [r["S0"] for r in q8["S0_table"]] + [_s12]
_m0 = statistics.mean(_s0); _sd0 = statistics.stdev(_s0)
from importlib import import_module
import sys as _sys; _sys.path.insert(0, ROOT)
_nmin = import_module("bmr.bounds").n_min
lines.append(mc("qEightNRuns", len(_s0), "number of ibm_marrakesh runs (9 in q8_hardware_reconcile + 12 Oct job db659bklf4us73c4qju0)"))
lines.append(mc("qEightSzeroMean", _m0, "mean S_hat(phi=0), ten marrakesh runs", fmt=".3f"))
lines.append(mc("qEightSzeroSD", _sd0, "SD S_hat(phi=0), ten runs", fmt=".3f"))
lines.append(mc("qEightSzeroSE", _sd0 / len(_s0) ** 0.5, "standard error of the mean, ten runs", fmt=".3f"))
lines.append(mc("qEightSzeroTwelveOct", _s12, "S_hat(phi=0) of the 12 Oct run (job db659bklf4us73c4qju0)", fmt=".3f"))
lines.append(mc("qEightNminAtMean", _nmin(_m0, 1e-6), "n_min(mean S0, delta=1e-6), eta_tight"))
lines.append(mc("qEightAerNoisySzero", q8["aer_noisy_S0"], "Aer noisy S(0)", fmt=".3f"))
lines.append(mc("qEightAerIdealSzero", q8["aer_ideal_S0"], "Aer ideal S(0)", fmt=".3f"))
lines += ["", "% === Q11 ALG3 TIMING ==="]
q11 = _ld("q11_alg3_v2.json")
tm4 = q11["timing_ed25519"]["4"]; tm11 = q11.get("timing_ed25519", {}).get("11", tm4)
lines.append(mc("qElevenTimingMean4hopsUs", tm4["total_us_mean"], "mean µs total, 4-hop ledger, Ed25519", fmt=".0f"))
lines.append(mc("qElevenTimingSD4hopsUs", tm4["total_us_sd"], "SD µs total, 4-hop ledger", fmt=".0f"))
lines.append(mc("qElevenTimingPerEntryMean4hopsUs", tm4["per_entry_us_mean"], "mean µs per entry (4 hops)", fmt=".0f"))
lines += ["", "% === Q15 DRIFT ROBUSTNESS ==="]
q15dr = json.load(open(os.path.join(RES, "q15_drift_robustness.json")))
base_n1e4_phi99 = [r for r in q15dr["rows"] if r["n"] == 10000 and r["phi"] == 0.99 and r["variant"] == "base"]
if base_n1e4_phi99:
    r = base_n1e4_phi99[0]
    lines.append(mc("qFifteenFABaseNe4phi99", r["fa"] * 100, "false-alarm % n=1e4 phi=0.99 base", fmt=".1f"))
    lines.append(mc("qFifteenDelayBaseNe4phi99", r["delay"], "detection delay epochs n=1e4 phi=0.99 base", fmt=".1f"))
    lines.append(mc("qFifteenViolBaseNe4phi99", r["viol"] * 100, "budget-violation-when-accepted % n=1e4 phi=0.99 base", fmt=".1f"))
lines += ["", "% === Q6 SWEEP: refusal, budget-only deltas (both configurations) ==="]
def _mean(xs): return sum(xs) / len(xs)
for tag, fn in (("NinetyNine", "q6_sweep.json"), ("Ninety", "q6_sweep_phi09.json")):
    rows = _ld(fn)["rows"]
    bmr = [r for r in rows if r["router"] == "BMR"]
    lines.append(mc(f"qSixRefusalAllPhi{tag}", _mean([r["refusal_pct"] for r in bmr]), f"BMR refusal %, all cells, file {fn}", fmt=".1f"))
    for topo in sorted({r["topo"] for r in bmr}):
        lines.append(mc(f"qSixRefusal{topo.replace('-', '')}Phi{tag}", _mean([r["refusal_pct"] for r in bmr if r["topo"] == topo]), f"BMR refusal %, {topo}, file {fn}", fmt=".1f"))
    bo = {}
    for r in rows: bo.setdefault(r["router"], []).append(r["mean_rate_budget_only"])
    for other, nm in (("B1a-P_lambda(0.01)", "BOneA"), ("B2-BMR-NoFloor", "BTwo"), ("B3-Zhang-style", "BThree")):
        key = [k for k in bo if k.startswith(other[:3])]
        if key:
            lines.append(mc(f"qSixBudgetOnlyDeltaVs{nm}Phi{tag}", _mean(bo["BMR"]) - _mean(bo[key[0]]), f"BMR minus {key[0]}, budget-only mean rate, file {fn}", fmt="+.4f"))
for topo in ("line", "star"):
    rows = [r for r in _ld("q6_sweep_degenerate.json")["rows"] if r["topo"] == topo]
    for rt in sorted({r["router"] for r in rows}):
        sel = [r for r in rows if r["router"] == rt]
        lines.append(mc(f"qSixDeg{topo}Compl{rt.replace('-', '').replace('_', '').replace('(', '').replace(')', '').replace('.', '')}", _mean([r["compl_pct"] for r in sel]), f"{topo} {rt} compliance % (R_MIN applied)", fmt=".1f"))
lines += ["", "% === Q9b SPARSE TIMING (pre-check 2t+1 > N-1 applied) ==="]
